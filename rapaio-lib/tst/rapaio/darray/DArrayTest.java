        e = assertThrows(IllegalArgumentException.class, () -> g.seq(Shape.of(2, 3)).mm(g.seq(Shape.of(3, 2)), Order.S));
        assertEquals("Illegal askOrder value, must be Order.C or Order.F", e.getMessage());

        var t1 = g.seq(Shape.of(31, 42));
